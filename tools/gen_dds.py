#!/usr/bin/env python3
"""Generate the two SRCDIFF display files with exact DDS columns.

    python tools/gen_dds.py        -> src/QDDSSRC/SRCDIFFD.dspf  (27x132)
                                      src/QDDSSRC/SRCDIFFD8.dspf (24x80)

Hand-editing fixed-column DDS is error-prone (one column off = CPD7410),
so both files are written from the layout tables below. Both files have
the same field names; the viewer opens SRCDIFFD and falls back to
SRCDIFFD8 (with PREFIX(W8_)) when the device cannot show 27x132.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(HERE, "..", "src", "QDDSSRC")


class Dds:
    def __init__(self):
        self.out = []

    def _put(self, line):
        line = line.rstrip()
        assert len(line) <= 80, (len(line), line)
        self.out.append(line)

    @staticmethod
    def indcols(ind):
        # col 7 = and/or (blank); cols 8-16: up to three indicators,
        # each [N| ] + 2 digits (N in 8/11/14, number in 9-10/12-13/15-16)
        s = " "
        for p in (ind.split() if ind else []):
            s += p if p.startswith("N") else " " + p
        return s.ljust(10)

    def cmt(self, text=""):
        self._put(("     A*" + text)[:80])

    def kw(self, keyword, ind=""):
        """keyword-only line, keyword in col 45"""
        self._put("     A" + self.indcols(ind) + " " * 28 + keyword)

    def poskw(self, row, col, keyword):
        """unnamed positioned item such as DATE / TIME"""
        self._put("     A" + " " * 32 + str(row).rjust(3) + str(col).rjust(3) + keyword)

    def rec(self, name, keyword=""):
        self._put("     A" + " " * 10 + "R " + name.ljust(10) + " " * 16 + keyword)

    def fld(self, name, length, typ, dec, usage, row, col, keyword="", ind=""):
        # name 19-28, len 30-34 right, type 35, dec 36-37 right, usage 38,
        # row 39-41 right, col 42-44 right, keywords from 45
        line = "     A" + self.indcols(ind) + "  " + name.ljust(10)
        line += " " + str(length).rjust(5) + typ + str(dec).rjust(2) + usage
        line += str(row).rjust(3) + str(col).rjust(3) + keyword
        self._put(line)

    def const(self, row, col, text):
        body = text.replace("'", "''")
        head = "     A" + " " * 32 + str(row).rjust(3) + str(col).rjust(3) + "'"
        if len(head) + len(body) + 1 <= 80:
            self._put(head + body + "'")
            return
        room = 80 - len(head) - 1
        self._put(head + body[:room] + "-")
        rest = body[room:]
        while rest:
            chunk, rest = rest[:34], rest[34:]
            self._put("     A" + " " * 38 + chunk + ("-" if rest else "'"))

    def colours(self):
        self.kw("COLOR(RED)", "31")
        self.kw("COLOR(GRN)", "32")
        self.kw("COLOR(BLU)", "33")
        self.kw("COLOR(YLW)", "34")
        self.kw("COLOR(WHT)", "35")

    def text(self):
        return "\n".join(self.out) + "\n"


def build(wide):
    """wide=True: SRCDIFFD 27x132, False: SRCDIFFD8 24x80"""
    d = Dds()
    if wide:
        name, size, sfl, ctl, foot = "SRCDIFFD", "DSPSIZ(27 132 *DS4)", "SFL1", "SFLCTL1", "FOOTER"
        txtlen, page, msglen, msgrow, keyrow = 113, 19, 100, 26, 27
    else:
        name, size, sfl, ctl, foot = "SRCDIFFD8", "DSPSIZ(24 80 *DS3)", "SFL8", "SFLCTL8", "FOOTER8"
        txtlen, page, msglen, msgrow, keyrow = 61, 16, 78, 23, 24
    last = 5 + page

    d.cmt("****************************************************************")
    d.cmt(" %-9s - SRCDIFF display: git-style unified compare, %s" % (name, "27x132" if wide else "24x80"))
    d.cmt(" Generated by tools/gen_dds.py - edit the generator, not this file")
    d.cmt(" Subfile colours: 31 deleted (red) 32 added (green) 33 hunk")
    d.cmt("   header (blue) 34 stats (yellow) 35 context (white)")
    d.cmt(" 27 page down 28 page up 29 SFLEND 30 show subfile (off = clear)")
    d.cmt("****************************************************************")
    d.kw(size)
    d.kw("CF03(03 'Exit')")
    d.kw("CF06(06 'Whole/Hunks')")
    d.kw("CF10(10 'Next change')")
    d.kw("CF11(11 'Previous change')")
    d.kw("CF12(12 'Cancel')")
    d.kw("CF14(14 'Ignore blanks')")
    d.kw("CF16(16 'Top')")
    d.kw("CF17(17 'Bottom')")
    if not wide:
        d.kw("CF19(19 'Shift left')")
        d.kw("CF20(20 'Shift right')")
    d.kw("PAGEDOWN(27 'Next page')")
    d.kw("PAGEUP(28 'Previous page')")
    d.kw("PRINT")
    d.kw("INDARA")

    d.cmt("---------------------------------------------------------------")
    d.cmt(" Subfile record: one diff row")
    d.cmt("---------------------------------------------------------------")
    d.rec(sfl, "SFL")
    d.fld("MK", 1, "A", "", "O", 6, 2)
    d.colours()
    d.fld("OSEQ", 7, "A", "", "O", 6, 4)
    d.colours()
    d.fld("NSEQ", 7, "A", "", "O", 6, 12)
    d.colours()
    d.fld("TXT", txtlen, "A", "", "O", 6, 20)
    d.colours()

    d.cmt("---------------------------------------------------------------")
    d.cmt(" Subfile control: header rows 1-5, page rows 6-%d, More... %d" % (last, last + 1))
    d.cmt("---------------------------------------------------------------")
    d.rec(ctl, "SFLCTL(%s)" % sfl)
    d.kw("SFLSIZ(%04d)" % page)
    d.kw("SFLPAG(%04d)" % page)
    d.kw("OVERLAY")
    d.kw("SFLDSP", "30")
    d.kw("SFLDSPCTL")
    d.kw("SFLCLR", "N30")
    d.kw("SFLEND(*MORE)", "29")
    if wide:
        d.const(1, 2, "SRCDIFF"); d.kw("COLOR(BLU)")
        d.const(1, 56, "Source Member Compare"); d.kw("DSPATR(HI)")
        d.poskw(1, 115, "DATE"); d.kw("EDTCDE(Y)"); d.kw("COLOR(BLU)")
        d.poskw(1, 125, "TIME"); d.kw("COLOR(BLU)")
        d.const(2, 2, "Old . . :"); d.kw("COLOR(BLU)")
        d.fld("OLDNAM", 33, "A", "", "O", 2, 12); d.kw("COLOR(RED)")
        d.const(2, 72, "Context . . . :"); d.kw("COLOR(BLU)")
        d.fld("CTXTXT", 5, "A", "", "O", 2, 88)
        d.const(2, 96, "Ignore blanks . :"); d.kw("COLOR(BLU)")
        d.fld("IGNTXT", 3, "A", "", "O", 2, 114)
        d.const(3, 2, "New . . :"); d.kw("COLOR(BLU)")
        d.fld("NEWNAM", 33, "A", "", "O", 3, 12); d.kw("COLOR(GRN)")
        d.const(3, 72, "Result  . . . :"); d.kw("COLOR(BLU)")
        d.fld("STATS", 36, "A", "", "O", 3, 88); d.kw("COLOR(YLW)")
        d.const(4, 2, "Go to seq . . ."); d.kw("COLOR(BLU)")
        d.fld("GOTOSEQ", 6, "Y", 2, "B", 4, 18, "EDTCDE(4)")
        d.kw("DSPATR(UL)")
        d.fld("POSTXT", 40, "A", "", "O", 4, 72); d.kw("COLOR(BLU)")
    else:
        d.const(1, 2, "SRCDIFF"); d.kw("COLOR(BLU)")
        d.const(1, 30, "Source Member Compare"); d.kw("DSPATR(HI)")
        d.poskw(1, 63, "DATE"); d.kw("EDTCDE(Y)"); d.kw("COLOR(BLU)")
        d.poskw(1, 72, "TIME"); d.kw("COLOR(BLU)")
        d.const(2, 2, "Old:"); d.kw("COLOR(BLU)")
        d.fld("OLDNAM", 33, "A", "", "O", 2, 7); d.kw("COLOR(RED)")
        d.const(2, 42, "Context:"); d.kw("COLOR(BLU)")
        d.fld("CTXTXT", 5, "A", "", "O", 2, 51)
        d.const(2, 58, "Ign blanks:"); d.kw("COLOR(BLU)")
        d.fld("IGNTXT", 3, "A", "", "O", 2, 70)
        d.const(3, 2, "New:"); d.kw("COLOR(BLU)")
        d.fld("NEWNAM", 33, "A", "", "O", 3, 7); d.kw("COLOR(GRN)")
        d.fld("STATS", 36, "A", "", "O", 3, 42); d.kw("COLOR(YLW)")
        d.const(4, 2, "Go to seq"); d.kw("COLOR(BLU)")
        d.fld("GOTOSEQ", 6, "Y", 2, "B", 4, 12, "EDTCDE(4)")
        d.kw("DSPATR(UL)")
        d.fld("POSTXT", 40, "A", "", "O", 4, 40); d.kw("COLOR(BLU)")
    d.const(5, 7, "Old#    New# Source"); d.kw("COLOR(BLU)"); d.kw("DSPATR(UL)")

    d.cmt("---------------------------------------------------------------")
    d.cmt(" Footer: message line and function keys")
    d.cmt("---------------------------------------------------------------")
    d.rec(foot)
    d.kw("OVERLAY")
    d.fld("MSG", msglen, "A", "", "O", msgrow, 2); d.kw("COLOR(PNK)")
    if wide:
        d.const(keyrow, 2, "F3=Exit   F6=Whole/Hunks   F10=Next change   "
                           "F11=Previous change   F14=Ignore blanks   F16=Top   "
                           "F17=Bottom   F12=Cancel")
    else:
        d.const(keyrow, 2, "F3=Exit F6=All F10/F11=Next/Prev F14=Blanks "
                           "F16/F17=Top/Bot F19/F20=Shift")
    d.kw("COLOR(BLU)")
    return name, d.text()


def main():
    for wide in (True, False):
        name, src = build(wide)
        path = os.path.join(OUTDIR, name + ".dspf")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(src)
        print("%s: %d lines" % (path, src.count("\n")))


if __name__ == "__main__":
    main()
