-- SRCDIFF build as ACS "Run SQL Scripts" CL: lines (one job, no BUILD program).
-- Replace MYLIB (objects) and MYSRCLIB (source files) first, then run all.
CL: ADDLIBLE LIB(MYSRCLIB);
CL: CRTDSPF FILE(MYLIB/SRCDIFFD) SRCFILE(MYSRCLIB/QDDSSRC) RSTDSP(*YES) REPLACE(*YES);
CL: CRTDSPF FILE(MYLIB/SRCDIFFD8) SRCFILE(MYSRCLIB/QDDSSRC) RSTDSP(*YES) REPLACE(*YES);
CL: CRTSQLRPGI OBJ(MYLIB/SRCDIFFM) SRCFILE(MYSRCLIB/QRPGLESRC) OBJTYPE(*MODULE) OPTION(*SYS) COMMIT(*NONE) RPGPPOPT(*LVL2) DBGVIEW(*SOURCE) REPLACE(*YES);
CL: CRTRPGMOD MODULE(MYLIB/SRCDIFFR) SRCFILE(MYSRCLIB/QRPGLESRC) DBGVIEW(*SOURCE) REPLACE(*YES);
CL: CRTPGM PGM(MYLIB/SRCDIFFR) MODULE(MYLIB/SRCDIFFR MYLIB/SRCDIFFM) ACTGRP(*NEW) REPLACE(*YES);
CL: CRTBNDCL PGM(MYLIB/SRCDIFFC) SRCFILE(MYSRCLIB/QCLLESRC) DBGVIEW(*SOURCE) REPLACE(*YES);
CL: CRTCMD CMD(MYLIB/SRCDIFF) PGM(MYLIB/SRCDIFFC) SRCFILE(MYSRCLIB/QCMDSRC) REPLACE(*YES);
-- Optional test driver (only needed to run the regression check in tools/):
CL: CRTPF FILE(MYLIB/SRCDIFFTP) SRCFILE(MYSRCLIB/QDDSSRC) SIZE(*NOMAX);
CL: CRTSQLRPGI OBJ(MYLIB/SRCDIFFT) SRCFILE(MYSRCLIB/QRPGLESRC) OBJTYPE(*MODULE) OPTION(*SYS) COMMIT(*NONE) RPGPPOPT(*LVL2) DBGVIEW(*SOURCE) REPLACE(*YES);
CL: CRTPGM PGM(MYLIB/SRCDIFFT) MODULE(MYLIB/SRCDIFFT MYLIB/SRCDIFFM) ACTGRP(*NEW) REPLACE(*YES);
